// 答案判定一律先 norm()：去空白與標點、全形轉半形、英文轉大寫。

export function norm(s) {
  return String(s ?? '')
    .replace(/[！-～]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/[\s　、，,。.．：:；;「」『』（）()〈〉《》！!？?\-—_／/]/g, '')
    .toUpperCase();
}

